/**
 * Runs every retrieval method over each sample corpus and writes the rankings
 * to docs/RESULTS.md, so the numbers quoted in the README are generated rather
 * than hand-copied. Run with `npm run results`.
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import { PRESETS } from '../src/data/presets.js'
import {
  bm25,
  cosineSim,
  crossEncoderScore,
  embedText,
  fuseRRF,
  maxSim,
  rankBy,
  splitSentences,
  RRF_K,
} from '../src/lib/retrieval.js'

function rankTable(rows, columns) {
  const header = `| ${columns.map(c => c.label).join(' | ')} |`
  const divider = `|${columns.map(() => '---').join('|')}|`
  const body = rows.map(r => `| ${columns.map(c => c.value(r)).join(' | ')} |`).join('\n')
  return [header, divider, body].join('\n')
}

function analyse(preset) {
  const { query, docs, document } = preset
  const queryVec = embedText(query)

  const dense = rankBy(
    docs.map(d => ({ ...d, score: cosineSim(queryVec, embedText(d.text)) })),
    d => d.score,
  )
  const sparse = rankBy(bm25(query, docs), d => d.score)
  const cross = rankBy(
    docs.map(d => ({ ...d, score: crossEncoderScore(query, d.text) })),
    d => d.score,
  )
  const colbert = rankBy(
    docs.map(d => ({ ...d, ...maxSim(query, d.text) })),
    d => d.total,
  )

  const denseRanks = Object.fromEntries(dense.map(d => [d.id, d.rank]))
  const sparseRanks = Object.fromEntries(sparse.map(d => [d.id, d.rank]))
  const fused = fuseRRF(
    docs.map(d => d.id),
    [{ label: 'BM25', ranks: sparseRanks }, { label: 'Dense', ranks: denseRanks }],
  ).sort((a, b) => b.score - a.score || a.id.localeCompare(b.id))

  const sentences = splitSentences(document)
  const vectors = sentences.map(embedText)
  const sims = vectors.slice(0, -1).map((v, i) => cosineSim(v, vectors[i + 1]))

  return { dense, sparse, cross, colbert, fused, denseRanks, sparseRanks, sentences, sims }
}

const sections = PRESETS.map(preset => {
  const a = analyse(preset)
  const byId = Object.fromEntries(preset.docs.map(d => [d.id, d.text]))

  const combined = preset.docs.map(d => ({
    id: d.id,
    text: byId[d.id],
    dense: a.dense.find(x => x.id === d.id),
    sparse: a.sparse.find(x => x.id === d.id),
    cross: a.cross.find(x => x.id === d.id),
    colbert: a.colbert.find(x => x.id === d.id),
    fused: a.fused.find(x => x.id === d.id),
  })).sort((x, y) => x.fused.score < y.fused.score ? 1 : x.fused.score > y.fused.score ? -1 : 0)

  const table = rankTable(combined, [
    { label: 'Doc', value: r => `\`${r.id}\`` },
    { label: 'Text', value: r => r.text },
    { label: 'BM25', value: r => `#${r.sparse.rank} · ${r.sparse.score.toFixed(3)}` },
    { label: 'Dense', value: r => `#${r.dense.rank} · ${r.dense.score.toFixed(3)}` },
    { label: 'Cross-enc', value: r => `#${r.cross.rank} · ${r.cross.score.toFixed(3)}` },
    { label: 'ColBERT', value: r => `#${r.colbert.rank} · ${r.colbert.total.toFixed(3)}` },
    { label: 'Hybrid RRF', value: r => r.fused.score.toFixed(5) },
  ])

  const weakest = a.sims.length ? Math.min(...a.sims) : 0
  const strongest = a.sims.length ? Math.max(...a.sims) : 0
  const boundary = a.sims.indexOf(weakest)

  const bm25Zero = a.sparse.every(d => d.score === 0)

  return `### ${preset.label}

**Query:** _${preset.query}_

${table}

**Chunking:** ${a.sentences.length} sentences · adjacent similarity ranges ${weakest.toFixed(3)}–${strongest.toFixed(3)} · the weakest boundary is between S${boundary + 1} and S${boundary + 2}, which is where semantic chunking splits first.

**Observation:** ${
    bm25Zero
      ? 'no query term appears literally in any document, so BM25 scores everything zero and the fused ranking is carried entirely by the dense retriever — the lexical gap hybrid search exists to close.'
      : `top-ranked \`${combined[0].id}\` placed #${combined[0].sparse.rank} in BM25 and #${combined[0].dense.rank} in dense retrieval.${
          combined[0].sparse.rank !== combined[0].dense.rank
            ? ' It topped neither list outright — RRF rewards consistency across both.'
            : ' Both retrievers agreed on it.'
        }`
  }`
}).join('\n\n---\n\n')

const out = `# Results

Generated by \`npm run results\` — every number below is produced by the same
functions the app runs in the browser (\`src/lib/retrieval.js\`), so this file
and the live site can never drift apart.

Reciprocal Rank Fusion uses k = ${RRF_K}. Embeddings are hashed character-trigram
bags, not a trained model: related word forms share features, which is enough to
reproduce the behaviour each method is known for.

${sections}
`

mkdirSync('docs', { recursive: true })
writeFileSync('docs/RESULTS.md', out)
console.log(out)
